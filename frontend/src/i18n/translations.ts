export const messages = { en, es } as const;

export type MessageTree = typeof en;
export type TranslateVars = Record<string, string | number>;

type Join<Left extends string, Right extends string> = Left extends ""
  ? Right
  : `${Left}.${Right}`;

type Leaves<T, Path extends string = ""> = T extends string
  ? Path
  : {
      [K in keyof T & string]: Leaves<T[K], Join<Path, K>>;
    }[keyof T & string];

export type MessageKey = Leaves<MessageTree>;

function lookup(tree: DeepString<MessageTree>, key: MessageKey): string {
  const parts = key.split(".");
  let current: unknown = tree;
  for (const part of parts) {
    if (typeof current !== "object" || current === null || !(part in current)) {
      return key;
    }
    current = (current as Record<string, unknown>)[part];
  }
  return typeof current === "string" ? current : key;
}

export function translate(locale: Locale, key: MessageKey, vars?: TranslateVars): string {
  return interpolate(lookup(messages[locale], key), vars);
}

